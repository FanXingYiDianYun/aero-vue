/**
 * 形状归一化：把 SVG 原生形状（circle/rect/ellipse）统一转为 path d 指令，
 * 使所有组件可以一律用 <path :d> 渲染（lucide 源数据为多元素节点）
 */
function shapeToPath(seg: string): string {
  const attrs: Record<string, number> = {}
  for (const kv of seg.split(/\s+/).slice(1)) {
    const m = /^([\w-]+)=([\d.]+)$/.exec(kv)
    if (m) attrs[m[1]] = Number(m[2])
  }
  if (/^circle /.test(seg)) {
    const { cx = 12, cy = 12, r = 4 } = attrs
    return `M ${cx - r} ${cy} a ${r} ${r} 0 1 0 ${r * 2} 0 a ${r} ${r} 0 1 0 -${r * 2} 0`
  }
  if (/^ellipse /.test(seg)) {
    const { cx = 12, cy = 12, rx = 9, ry = 3 } = attrs
    return `M ${cx - rx} ${cy} a ${rx} ${ry} 0 1 0 ${rx * 2} 0 a ${rx} ${ry} 0 1 0 -${rx * 2} 0`
  }
  if (/^rect /.test(seg)) {
    const { x = 3, y = 3, width = 18, height = 18, rx = 2 } = attrs
    const r = Math.min(rx, width / 2, height / 2)
    return [
      `M ${x + r} ${y}`,
      `h ${width - r * 2}`,
      `a ${r} ${r} 0 0 1 ${r} ${r}`,
      `v ${height - r * 2}`,
      `a ${r} ${r} 0 0 1 -${r} ${r}`,
      `h -${width - r * 2}`,
      `a ${r} ${r} 0 0 1 -${r} -${r}`,
      `v -${height - r * 2}`,
      `a ${r} ${r} 0 0 1 ${r} -${r}`,
      'z',
    ].join(' ')
  }
  if (/^polygon |^polyline |^line /.test(seg)) {
    const m = /points=([\d.,\s]+)/.exec(seg)
    if (!m) return ''
    const pts = m[1].trim().split(/[\s,]+/).map(Number)
    if (/^line /.test(seg)) {
      const [x1, y1, x2, y2] = pts
      return `M ${x1} ${y1} L ${x2} ${y2}`
    }
    const d = pts.reduce((acc, v, i) => (i % 2 === 0 ? [...acc, `${i ? 'L' : 'M'} ${v}`] : [...acc.slice(0, -1), `${acc[acc.length - 1]} ${v}`]), [] as string[])
    return d.join(' ') + (/^polygon /.test(seg) ? ' z' : '')
  }
  return seg
}

